internal enum HeapType {
    case maxHeap
    case minHeap

    internal func comparator<Element: Comparable>(type _: Element.Type) -> (Element, Element) -> Bool {
        switch self {
        case .maxHeap:
            return (>)

        case .minHeap:
            return (<)
        }
    }
}
