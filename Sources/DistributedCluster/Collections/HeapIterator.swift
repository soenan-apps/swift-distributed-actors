internal struct HeapIterator<Element: Equatable>: IteratorProtocol {
    private var heap: Heap<Element>

    internal init(heap: Heap<Element>) {
        self.heap = heap
    }

    internal mutating func next() -> Element? {
        self.heap.removeRoot()
    }
}
